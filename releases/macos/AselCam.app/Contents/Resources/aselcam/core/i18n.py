class I18nManager:
    _instance = None

    def __init__(self):
        self._current_lang = "tr"
        self._listeners: List[Callable[[], None]] = []

    @classmethod
    def get_instance(cls) -> "I18nManager":
        if cls._instance is None:
            cls._instance = I18nManager()
        return cls._instance

    @property
    def current_language(self) -> str:
        return self._current_lang

    def set_language(self, lang_code: str):
        if lang_code == "auto":
            lang_code = self._detect_system_language()

        if lang_code in TRANSLATIONS:
            self._current_lang = lang_code
            for callback in self._listeners:
                try:
                    callback()
                except Exception:
                    pass

    def register_listener(self, callback: Callable[[], None]):
        if callback not in self._listeners:
            self._listeners.append(callback)

    def unregister_listener(self, callback: Callable[[], None]):
        if callback in self._listeners:
            self._listeners.remove(callback)

    def translate(self, key: str, **kwargs) -> str:
        lang_dict = TRANSLATIONS.get(self._current_lang, TRANSLATIONS.get("en", {}))
        val = lang_dict.get(key)
        if val is None:
            val = TRANSLATIONS.get("en", {}).get(key, key)
        if kwargs:
            try:
                return val.format(**kwargs)
            except Exception:
                return val
        return val

    def _detect_system_language(self) -> str:
        try:
            default_locale, _ = locale.getdefaultlocale()
            if default_locale:
                code = default_locale.split("_")[0].lower()
                if code in TRANSLATIONS:
                    return code
        except Exception:
            pass

        for env_var in ("LC_ALL", "LC_MESSAGES", "LANG"):
            val = os.environ.get(env_var, "")
            if val:
                code = val.split(".")[0].split("_")[0].lower()
                if code in TRANSLATIONS:
                    return code
        return "tr"

def _t(key: str, **kwargs) -> str:
    return I18nManager.get_instance().translate(key, **kwargs)

tr = _t

def detect_system_language() -> str:
    return I18nManager.get_instance()._detect_system_language()


